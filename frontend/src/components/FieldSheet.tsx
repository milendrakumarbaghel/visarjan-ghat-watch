const tierStyle: Record<Tier, string> = {
  HIGH: 'bg-red-600 text-white',
  MEDIUM: 'bg-amber-300 text-amber-950',
  LOW: 'bg-slate-200 text-slate-800',
}

function dateText(d: Date, lang: Lang) {
  return d.toLocaleDateString(lang === 'hi' ? 'hi-IN' : 'en-IN', { day: 'numeric', month: 'short' })
}

/** The most recent printed value for a parameter at this ghat, preferring the during-immersion sample. */
function lastResult(readings: ReadingView[], parameter: string, lang: Lang) {
  const rows = readings
    .filter((r) => r.parameter === parameter && r.status !== 'MISSING')
    .sort((a, b) => b.year - a.year || (a.festival === b.festival ? 0 : a.festival === 'Durga' ? -1 : 1))
  if (rows.length === 0) return null
  const latest = rows.filter((r) => r.year === rows[0].year && r.festival === rows[0].festival)
  const pick = latest.find((r) => r.phase === 'during') ?? latest[0]
  return `${pick.status === 'BELOW_DETECTION' ? pick.flag ?? 'BDL' : fmt(pick.value)} (${festivalLabel(pick.festival, pick.year, lang)})`
}

export function FieldSheet({
  ghat,
  plan,
  readings,
  lang,
  newPage,
}: {
  ghat: GhatRisk
  plan: PlanView | undefined
  readings: ReadingView[]
  lang: Lang
  newPage?: boolean
}) {
  const i = lang === 'hi' ? 1 : 0
  const tx = (k: keyof typeof L) => L[k][i]
  const actions = actionsFor(ghat, plan)
  const reasons = ghat.reasons.filter((r) => r.tone !== 'ok').slice(0, 4)

  return (
    <article lang={lang} data-pdf-page-start={newPage || undefined} className="bg-white pt-1 text-[10pt] leading-snug text-slate-900">
      <header className="flex items-center gap-3 border-b-[3px] border-brand-700 pb-2.5">
        <img src="/images/mp-emblem.png" alt="" className="size-[18mm] shrink-0" />
        <div className="flex-1">
          <div className="text-[10pt] font-bold tracking-wide text-brand-800 uppercase">{tx('govt')}</div>
          <div className="text-[9pt] text-slate-600">{tx('title')}</div>
          <h1 className="text-[16pt] leading-tight font-extrabold text-ink-900">{lang === 'hi' ? ghat.nameHi : ghat.name}</h1>
          <div className="text-[9pt] text-slate-600">{lang === 'hi' ? ghat.waterBodyHi : ghat.waterBody}</div>
        </div>
        <div className="shrink-0 text-right">
          <span className={`inline-block rounded px-2 py-0.5 text-[9pt] font-bold ${tierStyle[ghat.tier]}`}>
            {lang === 'hi' ? ghat.tierLabelHi : ghat.tierLabel}
          </span>
          <div className="mt-1 text-[8.5pt] text-slate-600">
            {tx('score')} {fmt(ghat.score, 1)}/100 · {tx('rank')} {ghat.rank}/7
          </div>
        </div>
      </header>

      <section className="mt-3">
        <h2 className="mb-1 border-l-4 border-brand-600 bg-brand-50 py-0.5 pl-2 text-[10.5pt] font-bold text-brand-900">{tx('why')}</h2>
        <ul className="list-disc space-y-0.5 pl-5 text-[9pt]">
          {reasons.map((r, n) => (
            <li key={n}>{lang === 'hi' ? r.hi : r.en}</li>
          ))}
        </ul>
      </section>

      <section className="mt-3">
        <h2 className="mb-1 border-l-4 border-brand-600 bg-brand-50 py-0.5 pl-2 text-[10.5pt] font-bold text-brand-900">
          {tx('actions')} <span className="text-[8.5pt] font-medium text-slate-500">({plan?.saved ? tx('planned') : tx('suggested')})</span>
        </h2>
        <ul className="space-y-1 text-[9.5pt]">
          {[...actions.map((a) => translate(lang, a)), tx('samples')].map((a) => (
            <li key={a} className="flex items-center gap-2">
              <span className="inline-block size-[4mm] shrink-0 rounded-sm border-[1.5px] border-slate-500" aria-hidden />
              {a}
            </li>
          ))}
        </ul>
        {plan?.saved && plan.note && <p className="mt-1 text-[9pt] text-slate-600 italic">{plan.note}</p>}
      </section>

      <section className="mt-3">
        <h2 className="mb-1 border-l-4 border-brand-600 bg-brand-50 py-0.5 pl-2 text-[10.5pt] font-bold text-brand-900">{tx('readings')}</h2>
        <table className="w-full border-collapse text-[8.5pt]">
          <thead>
            <tr className="bg-ink-900 text-white">
              <th className="border border-ink-900 px-1.5 py-1 text-left">{tx('parameter')}</th>
              <th className="border border-ink-900 px-1.5 py-1 text-left">{tx('limit')}</th>
              <th className="border border-ink-900 px-1.5 py-1 text-left">{tx('last')}</th>
              {TEST_DATES.map((d) => (
                <th key={d.phase} className="w-[22mm] border border-ink-900 px-1.5 py-1 text-center">
                  {translate(lang, d.phase)}
                  <div className="font-normal opacity-80">{dateText(d.date, lang)}</div>
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {PARAMETERS.map((p, n) => {
              const limit = CLASS_B[p.name]
              return (
                <tr key={p.name} className={n % 2 ? 'bg-slate-50' : ''}>
                  <td className="border border-slate-300 px-1.5 py-[3px] font-medium">
                    {lang === 'hi' ? p.hi : p.name}
                    {p.unit && <span className="text-slate-500"> ({p.unit})</span>}
                  </td>
                  <td className={`border border-slate-300 px-1.5 py-[3px] ${limit ? 'font-semibold' : 'text-slate-400'}`}>
                    {limit ? limit.text : tx('noLimit')}
                  </td>
                  <td className="border border-slate-300 px-1.5 py-[3px] text-slate-600">{lastResult(readings, p.name, lang) ?? tx('none')}</td>
                  {TEST_DATES.map((d) => (
                    <td key={d.phase} className="border border-slate-300" />
                  ))}
                </tr>
              )
            })}
            <tr>
              <td className="border border-slate-300 px-1.5 py-[3px] font-medium">{tx('coliform')}</td>
              <td className="border border-slate-300 px-1.5 py-[3px] font-semibold">{tx('coliformLimit')}</td>
              <td className="border border-slate-300 px-1.5 py-[3px] text-slate-500 italic">{tx('notTested')}</td>
              {TEST_DATES.map((d) => (
                <td key={d.phase} className="border border-slate-300" />
              ))}
            </tr>
          </tbody>
        </table>
        <p className="mt-1 text-[8pt] text-slate-500">{tx('howTo')}</p>
      </section>

      <section className="mt-3">
        <h2 className="mb-1 border-l-4 border-brand-600 bg-brand-50 py-0.5 pl-2 text-[10.5pt] font-bold text-brand-900">{tx('notes')}</h2>
        <div className="space-y-[6mm] pt-2">
          {[0, 1, 2].map((n) => (
            <div key={n} className="border-b border-slate-300" />
          ))}
        </div>
      </section>

      <div className="mt-5 grid grid-cols-4 gap-4 text-[8.5pt]">
        {(['team', 'designation', 'signature', 'date'] as const).map((k) => (
          <div key={k} className="border-b border-slate-400 pb-1 text-slate-500">
            {tx(k)}:
          </div>
        ))}
      </div>

      <footer className="mt-3 border-t border-slate-300 pt-1.5 text-[7.5pt] text-slate-500">{tx('footer')}</footer>
    </article>
  )
}
